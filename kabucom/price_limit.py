"""
東証の制限値幅（ストップ高・ストップ安の幅）

基準値段（通常は前日終値）に応じて1日の値幅が決まる。
値幅拡大などの特例は考慮しない。
"""
from __future__ import annotations

# (基準値段がこの値未満, 制限値幅)
_LIMITS = [
    (100, 30), (200, 50), (500, 80), (700, 100), (1000, 150),
    (1500, 300), (2000, 400), (3000, 500), (5000, 700), (7000, 1000),
    (10000, 1500), (15000, 3000), (20000, 4000), (30000, 5000), (50000, 7000),
    (70000, 10000), (100000, 15000), (150000, 30000), (200000, 40000), (300000, 50000),
    (500000, 70000), (700000, 100000), (1000000, 150000), (1500000, 300000),
    (2000000, 400000), (3000000, 500000), (5000000, 700000), (7000000, 1000000),
    (10000000, 1500000), (15000000, 3000000), (20000000, 4000000), (30000000, 5000000),
    (50000000, 7000000),
]


def limit_width(base_price: float) -> float:
    for upper, width in _LIMITS:
        if base_price < upper:
            return width
    return 10000000


def upper_limit(base_price: float) -> float:
    return base_price + limit_width(base_price)


def lower_limit(base_price: float) -> float:
    return max(base_price - limit_width(base_price), 1)
